// The below functions are simply for testing the Encode/Decode

#define BACKGROUNDS_TO_TRY          1000
#define CORRUPTIONS_PER_BACKGROUND  50000

#define CLRLINE "\x1b[2K\r"     // Line clearing escape sequence

uint64_t NextRand(uint64_t v)
{
    return (v >> 1) ^ ((v & 1) ? 0x8040000020000004 : 0);
}

int main(int argc, char* argv[])
{
    uint64_t codeword[10]; // RAIDDR-encoded codeword
    uint64_t userdata[8]; // Data to encode
    uint16_t metadata; // Metadata to encode
    uint64_t returnuserdata[8]; // Data from decoder
    uint16_t returnmetadata; // Metadata from decoder
    int ceDevice; // Telmetry - Device number that failed
    uint64_t ceMask; // Telemetry - Failure mask that had to be applied to ceDevice
    uint64_t* coeffA = NULL; // 'Short' CRC coefficients (used as crcconstants_s)
    uint64_t* coeffB = NULL; // Normal CRC coefficients (used as crcconstants) 

    uint64_t v, corruption; // temporary, corruption to apply to the codeword
    int d, result; // temporary, result from decode

    // Helper constants for the DDR5 10x4 4CW 4MD case
    const int metadatabits = 4;
    const int codeWords = 4;
    const int devices = 10;
    const int cwBitsPerDev = 64 / codeWords;
    const int cwSize = cwBitsPerDev * (devices - 1);

    // Simulation iterators and statistics
    const uint64_t bgToTest = BACKGROUNDS_TO_TRY; // 1000 error patterns to evaluate (default)
    const uint64_t errPerBg = CORRUPTIONS_PER_BACKGROUND; // 50000 error patterns per background (default)
    uint64_t bgNum;
    uint64_t errNum;
    uint64_t eval;
    uint64_t uecount;
    uint64_t sdccount;
    double totalden;

    // Create CRC coefficients
    // Note that the polynomial is only used to generate these coefficients
    // After that, there is nowhere it is used in the encode/decode
    coeffA = (uint64_t*)malloc(sizeof(uint64_t) * cwSize);
    CreateCrcCoefficients(cwSize, 0xE02, coeffA); // 0xE02 is a reverse, truncated, primitive polynomial for CRC-12
    if (codeWords > 1)
    {
        coeffB = (uint64_t*)malloc(sizeof(uint64_t) * cwSize);
        CreateCrcCoefficients(cwSize, 0x8029, coeffB); // 0x8029 is a reverse, truncated, primitive polynomial for CRC-16
    }
    metadata = 1; // Initialize Metadata

    // Initialize Userdata to random values
    v = userdata[0] = 0xABCDEF0123456789;
    for (d = 1; d < 8; d++)
        v = userdata[d] = NextRand(v); // LFSR for random data

    // Stage-1
    // We want to evaluate random backgrounds, random error patterns. This will cycle
    // through 'bgToTest' number different backgrounds and evaluate 'errPerBg' number
    // of different error cases for each background pattern.
    // We cycle through each device to take the error to not bias any specific device.
    // 
    // In reality, RAIDDR uses linear codes which makes it background-independent and
    // RAIDDR is technically device-position independent, but it's still valuable to
    // validate those claims in test.
    eval = 0;
    uecount = sdccount = 0;
    corruption = 1; // Initialize corruption data
    for (bgNum = 0; bgNum < bgToTest; bgNum++)
    {
        // Create new background...
        for (d = 0; d < 8; d++)
            userdata[d] = NextRand(userdata[d]); // LFSR randomization
        metadata = (metadata >> 1) ^ ((metadata & 1) ? 0xC : 0); // LFSR randomization

        // Raiddr encode the new background data
        EncodeRaiddr_D510x4(userdata, metadata, metadatabits, coeffA, coeffB, codeword);

        // Screen update
        if (eval)
        {
            printf(CLRLINE "Stage-1: %.1f%% (%" SCNu64 ") - SDC:%" SCNu64 " - UE:%" SCNu64 " (Pue=%.3le) (Gran=%.3le)", (double)eval * 100.0 / (double)bgToTest / (double)errPerBg, eval, sdccount, uecount, (double)uecount / (double)eval, 1.0 / (double)eval);
            fflush(stdout);
        }

        // Verify RAIDDR works when there is no corruption - Show on screen if this didn't work
        result = DecodeRaiddr_D510x4(codeword, metadatabits, coeffA, coeffB, returnuserdata, &returnmetadata, &ceDevice, &ceMask);
        if (result != 0)
            printf(CLRLINE " NoError Fail: result=%d\n", result);

        // Evaluate 'errPerBg' number of different corruption types with this background
        for (errNum = 0; errNum < errPerBg; errNum++) // This loop evaluates different data corruption cases
        {
            corruption = NextRand(corruption); // Next random data pattern (LFSR)
            // Decode corrupted Raiddr codeword and analyze results
            codeword[d] ^= corruption; // Add corruption to the codeword
            result = DecodeRaiddr_D510x4(codeword, metadatabits, coeffA, coeffB, returnuserdata, &returnmetadata, &ceDevice, &ceMask);
            codeword[d] ^= corruption; // Remove corruption from the codeword
            if (result == 2 || result == 3 || result == 4) // Uncorrectable error
                uecount++;
            else if (result == 0) // Decoder said data was good, but we know it wasn't
                sdccount++;
            else if (ceDevice != d || ceMask != corruption) // Corrected or said it's good, so let's verify the output
                sdccount++;
            eval++;
            if (++d >= devices) d = 0; // Apply corruption on next device for the next loop
        }
    }
    printf(CLRLINE "Stage-1 Summary: Evals=%" SCNu64 " SDC=%" SCNu64 " UE=%" SCNu64 " (%.3le)\n", eval, sdccount, uecount, (double)uecount / (double)eval);

    // Stage-2: Evaluate gap-capable patterns:
    // Now evaluate all error cases where the error is the same across all codewords
    // -- these are the only possible gap pattern cases for single-die failure
    // There are 15 total gap patterns in the DDR5 10x4 4-CW 4-MD configuration.
    // Assuming everything works properly, this step should fail 15/65536 (0.00022888 ratio)
    eval = 0;
    uecount = sdccount = 0;
    for (errNum = 1; errNum < (1 << 16); errNum++)
    {
        corruption = (uint64_t)errNum | ((uint64_t)errNum << 16) | ((uint64_t)errNum << 32) | ((uint64_t)errNum << 48); // Note duplicate error patterns in each codeword, these are where the gaps are
        for (d = 0; d < devices; d++) // Use the same corruption in all devices... this verifies for us that gaps are gaps for all devies
        {
            // Decode corrupted Raiddr codeword and analyze results
            codeword[d] ^= corruption; // Add corruption to the codeword
            result = DecodeRaiddr_D510x4(codeword, metadatabits, coeffA, coeffB, returnuserdata, &returnmetadata, &ceDevice, &ceMask);
            codeword[d] ^= corruption; // Remove corruption from the codeword
            if (result == 2 || result == 3 || result == 4) // Uncorrectable error
                uecount++;
            else if (result == 0) // Decoder said data was good, but we know it wasn't
                sdccount++;
            else if (ceDevice != d || ceMask != corruption) // Corrected or said it's good, so let's verify the output
                sdccount++;
            eval++;
        }
    }
    printf(CLRLINE "Stage-2 Summary: Evals=%" SCNu64 " SDC=%" SCNu64 " UE=%" SCNu64 " (%.3le)\n", eval, sdccount, uecount, (double)uecount / (double)eval);
    totalden = (1.0 + (double)((uint64_t)-1)) * 10.0; // 1^64 combinations on 10 different die
    printf(CLRLINE "Overall SDDC: SDC=%.3le UE=%.3le\n", (double)sdccount / totalden, (double)uecount / totalden);

    // Tidy up memory
    if (coeffA)
        free(coeffA);
    if (coeffB)
        free(coeffB);

    return 0;
}